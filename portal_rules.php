<?php
// portal_rules.php — server rules text + helpers.
// Rendered on /rules and in an expandable box on /register (with a mandatory
// "I accept" checkbox). The «SITE NAME» token is replaced by SITE_NAME.

if (function_exists('server_rules_text')) return;

function server_rules_text(): string {
    $t = <<<'EOT'
# ПРАВИЛА ИГРОВОГО СЕРВЕРА «SITE NAME»

### 1. ОБЩИЕ ПОЛОЖЕНИЯ

1.1. Настоящие Правила являются обязательными для всех игроков и распространяются на все аспекты игрового процесса на сервере «New Eden Prime».

1.2. Администрация сервера оставляет за собой право вносить изменения в Правила с обязательным уведомлением игроков за 24 часа до вступления изменений в силу.

1.3. Незнание Правил не освобождает игрока от ответственности за их нарушение.

---

### 2. ЗОНЫ PVP И ПРАВИЛА ВЗАИМОДЕЙСТВИЯ

| Зона | Правила PvP | Особые ограничения |
| :--- | :--- | :--- |
| **High-Sec (0.5 - 1.0)** | Агрессия без согласия **ЗАПРЕЩЕНА**. Включая атаку на корабли, капсулы, структуры игроков и использование варп-скрамблеров/дизрапторов. | Нарушение карается немедленным уничтожением корабля силами CONCORD. |
| **Low-Sec (0.1 - 0.4)** | Агрессия разрешена, но влечет за собой статус «Преступник» и активацию турелей у врат/станций. | Запрещена установка мобильных варп-дизрапторов («пузырей») у врат и станций. |
| **Null-Sec (0.0)** | Агрессия разрешена без ограничений. | Действует система суверенитета, установленная Правилами. |
| **W-Space (Червоточины)** | Агрессия разрешена без ограничений. | Действуют механики классов червоточин (C1-C6) и масс-лимиты. |

---

### 3. ПРАВИЛА СУВЕРЕНИТЕТА И ВЛАДЕНИЯ ТЕРРИТОРИЯМИ

3.1. **Установка суверенитета:**

   - Право на суверенитет в системе получает корпорация/альянс, установившая и активировавшая Территориальный модуль претензий (TCU) в системе без суверенитета.
   - Для установки суверенитета требуется не менее **7 дней** непрерывного контроля над системой.

3.2. **Оспаривание суверенитета:**

   - Захват суверенитета в системе, принадлежащей другой группе, без её письменного согласия (предоставленного администрации) – **ЗАПРЕЩЕН**.
   - Установка Модулей блокады суверенитета (SBU) без согласия владельца системы – **ЗАПРЕЩЕНА**.

3.3. **Ограничения для владельцев:**

   - Владелец системы **НЕ ИМЕЕТ ПРАВА** ограничивать доступ к станциям и вратам для других игроков (кроме случаев, связанных с PvP-событиями, анонсированными администрацией).
   - Установка налогов на станциях в системе НЕ МОЖЕТ превышать **15%** (за исключением территорий, выделенных для «Промышленных зон», где налог фиксирован на уровне **5%**).

3.4. **Защита структур:**

   - Атака на любые структуры игроков (POS, Upwell структуры, Аутпосты) в High-Sec и Low-Sec без согласия владельца – **ЗАПРЕЩЕНА**.
   - В Null-Sec атака структур разрешена, но с обязательным уведомлением владельца за **48 часов** до начала атаки (через систему внутриигровых сообщений или на форуме сервера).

---

### 4. ЭКОНОМИЧЕСКИЕ ОГРАНИЧЕНИЯ И ПРОТИВОДЕЙСТВИЕ ЭКСПЛОЙТАМ

4.1. **Защита рынка:**

   - Запрещено намеренное создание дисбаланса на внутриигровом рынке, включая скупку всего объема ключевых ресурсов (например, PLEX, Mega-SMB, Rorqual BPC) для искусственного завышения цен.
   - Максимальная цена на PLEX на сервере зафиксирована в пределах **2.500.000.000 ISK** (при превышении администрация проводит интервенцию).

4.2. **Защита индустрии:**

   - Запрещено монополизировать производство ключевых модулей Т2 и Т3 (например, компонентов для капитальных кораблей) без возможности их приобретения другими игроками по рыночной цене.

4.3. **Защита от дюпа и фарма:**

   - Использование любых багов/эксплойтов для дупликации предметов, ISK или навыков – **СТРОГО ЗАПРЕЩЕНО** и карается вечным баном с конфискацией всех активов.
   - Массовый фарм миссий/аномалий с использованием ботов или макросов – **ЗАПРЕЩЕН**.

---

### 5. ПРАВИЛА ДЛЯ КАПИТАЛЬНЫХ КОРАБЛЕЙ И СУПЕР-КОРАБЛЕЙ

5.1. **Ограничения на вход:**

   - Использование Дредноутов и Носителей в системах с уровнем безопасности **0.7 и выше** – **ЗАПРЕЩЕНО**.
   - Использование Супер-носителей и Титанов в системах с уровнем безопасности **0.5 и выше** – **ЗАПРЕЩЕНО**.

5.2. **Ограничения на дроны:**

   - Запрещено использование файтеров и файтер-бомберов в High-Sec системах (0.5 - 1.0).

5.3. **Осады и таймеры:**

   - Начало осады капитальными кораблями структур игроков в Null-Sec разрешено только после официального объявления войны на форуме сервера с указанием целей и сроков.

---

### 6. ОБЩИЕ ЗАПРЕТЫ НА ИГРОВОЕ ПОВЕДЕНИЕ

6.1. **Запрещено использование стороннего ПО:**

   - Любые программы, дающие игровое преимущество (боты, автокликеры, читы, программы для чтения памяти игры), строго запрещены.

6.2. **Запрет на троллинг/грифинг:**

   - Намеренное создание помех другим игрокам (например, блокировка ворот капитальными кораблями, массовый сброс контейнеров у станций) без игровой цели – **ЗАПРЕЩЕНО**.

6.3. **Запрет на оскорбления:**

   - Оскорбления, угрозы в реальной жизни, расизм, сексизм и другие формы дискриминации в любых каналах связи (локальный чат, корпоративный чат, флотный чат) – **ЗАПРЕЩЕНЫ**.

---

### 7. ИСКЛЮЧИТЕЛЬНЫЕ СЛУЧАИ (EVENT'Ы И ТЕСТИРОВАНИЯ)

7.1. Администрация оставляет за собой право проводить ивенты, временно изменяющие правила (например, «Битва за Мелонид», где разрешено всё во всех зонах).

7.2. Во время тестирования новых механик администрация может запросить помощь игроков в виде массовых PvP-сражений без последствий для игроков.

---

### 8. НАКАЗАНИЯ ЗА НАРУШЕНИЯ

| Нарушение | Наказание |
| :--- | :--- |
| **Оскорбления, троллинг, грифинг** | Предупреждение, затем бан на 7 дней, затем перманентный бан. |
| **Агрессия в High-Sec без согласия** | Уничтожение корабля (CONCORD), штраф 500M ISK в казну сервера, бан на 3 дня. |
| **Оспаривание суверенитета без согласия** | Конфискация всех SBU/TCU, штраф 1B ISK, бан на 7 дней. |
| **Дюп/Эксплойт/Боты** | Перманентный бан с конфискацией всех активов. |
| **Использование капитальных кораблей в High-Sec** | Конфискация корабля и перманентный бан аккаунта. |
EOT;
    return str_replace('«SITE NAME»', SITE_NAME, $t);
}
